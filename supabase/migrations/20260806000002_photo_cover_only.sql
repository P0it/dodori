-- 표지 전용 사진 — 앨범 커버로 쓰려고 따로 구해 올린 이미지.
--
-- 아직 사진이 없는 앞으로의 데이트에 커버부터 정하면(히어로 탭 → 새 이미지 업로드)
-- 그 이미지가 photos 행으로 들어가면서 그날의 사진 아카이브·갤러리·사진 수는 물론
-- 그 데이트 코스에 담긴 장소들의 '우리 사진'에까지 번졌다. 자켓은 수록곡이 아니다.
--
-- photos는 부모가 정확히 하나여야 하므로(num_nonnulls(track_id, post_id, story_id) = 1)
-- 부모 없이 둘 수는 없다 — track_id는 그대로 두고 이 플래그로 아카이브에서만 감춘다.
-- 갤러리에서 그날 사진 하나를 커버로 지정하는 경로는 false 그대로다 (그날의 사진이므로).
--
-- 커버가 바뀌거나 해제되면 이 사진은 클라이언트가 함께 지운다 — 아카이브에 안 보이니
-- 남겨두면 지울 길이 없는 고아가 되고 쿼터만 먹는다.
alter table public.photos add column cover_only boolean not null default false;
