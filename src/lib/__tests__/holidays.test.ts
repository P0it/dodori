/**
 * 공휴일 규칙 검증 — 기대값은 관보/KASI 공표 달력에서 가져온 실제 값이다.
 * (선거일·임시공휴일은 계산 대상이 아니므로 기대값에서 제외 — 서버 오버레이 담당)
 */
import { holidaysInYear, holidayMap, holidayMapForMonth } from '../holidays';

const dates = (year: number) => holidaysInYear(year).map((h) => h.date);

describe('holidaysInYear — 2026 (공표 달력 전체 대조)', () => {
  it('2026년 공휴일이 관보와 정확히 일치한다', () => {
    expect(dates(2026)).toEqual([
      '2026-01-01', // 신정
      '2026-02-16', // 설날 전날
      '2026-02-17', // 설날
      '2026-02-18', // 설날 다음 날
      '2026-03-01', // 삼일절 (일)
      '2026-03-02', // → 대체
      '2026-05-05', // 어린이날 (화)
      '2026-05-24', // 부처님오신날 (일)
      '2026-05-25', // → 대체
      '2026-06-06', // 현충일 (토) — 대체 없음
      '2026-08-15', // 광복절 (토)
      '2026-08-17', // → 대체 (일요일 건너뛰고 월요일)
      '2026-09-24', // 추석 전날
      '2026-09-25', // 추석
      '2026-09-26', // 추석 다음 날 (토) — 설·추석은 토요일 대체 없음
      '2026-10-03', // 개천절 (토)
      '2026-10-05', // → 대체
      '2026-10-09', // 한글날 (금)
      '2026-12-25', // 성탄절 (금)
    ]);
  });

  it('2026년 대체공휴일은 4회뿐이다', () => {
    const subs = holidaysInYear(2026).filter((h) => h.substitute);
    expect(subs.map((h) => h.date)).toEqual(['2026-03-02', '2026-05-25', '2026-08-17', '2026-10-05']);
  });
});

describe('음력 3종 (KASI 변환)', () => {
  it('설날 당일', () => {
    expect(holidayMap(2026)['2026-02-17']).toBe('설날');
    expect(holidayMap(2027)['2027-02-07']).toBe('설날');
  });

  it('추석 당일', () => {
    expect(holidayMap(2026)['2026-09-25']).toBe('추석');
    expect(holidayMap(2027)['2027-09-15']).toBe('추석');
  });

  it('부처님오신날', () => {
    expect(holidayMap(2026)['2026-05-24']).toBe('부처님오신날');
    expect(holidayMap(2027)['2027-05-13']).toBe('부처님오신날');
  });
});

describe('대체공휴일 규칙', () => {
  it('설날 연휴가 일요일과 겹치면 연휴 다음 첫 비공휴일이 대체 (2027: 2/7 일 → 2/9 화)', () => {
    const m = holidayMap(2027);
    expect(m['2027-02-08']).toBe('설날'); // 연휴 마지막 날(월)
    expect(m['2027-02-09']).toBe('대체공휴일(설날)');
  });

  it('토요일 공휴일은 일요일을 건너뛰고 월요일이 된다 — 앞으로 당기지 않는다', () => {
    // 2026 광복절 8/15(토) → 8/17(월). 8/14(금)이 되는 일은 없다.
    const m = holidayMap(2026);
    expect(m['2026-08-17']).toBe('대체공휴일(광복절)');
    expect(m['2026-08-14']).toBeUndefined();
  });

  it('현충일은 토요일과 겹쳐도 대체공휴일이 없다 (2026-06-06 토)', () => {
    const m = holidayMap(2026);
    expect(m['2026-06-06']).toBe('현충일');
    expect(m['2026-06-08']).toBeUndefined();
  });

  it('신정은 대체공휴일이 없다 (2028-01-01 토)', () => {
    const m = holidayMap(2028);
    expect(m['2028-01-01']).toBe('신정');
    expect(m['2028-01-03']).toBeUndefined();
  });
});

describe('holidayMapForMonth', () => {
  it('전후 연도를 물어 그리드 앞뒤 달을 덮는다 (2027-01 그리드는 2026-12-25를 본다)', () => {
    const m = holidayMapForMonth('2027-01');
    expect(m['2026-12-25']).toBe('성탄절');
    expect(m['2027-02-07']).toBe('설날');
  });

  it('서버 오버레이(임시공휴일)가 계산값을 덮어쓴다', () => {
    const m = holidayMapForMonth('2026-06', { '2026-06-03': '지방선거' });
    expect(m['2026-06-03']).toBe('지방선거');
  });
});
